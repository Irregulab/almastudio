// Builds packages/terminal-web into one self-contained HTML page and writes
// it to the companion app as a string module, so the WebView loads it with no
// files or server: `source={{ html }}`.
//
// Uses the desktop's xterm.js and Vite, so the app's terminal renders exactly
// as the desktop's does. Run from the repository root: `npm run build:terminal`.
import { build } from 'vite'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = join(root, 'packages/terminal-web')
const outDir = join(pkg, 'dist')

await build({
  root: pkg,
  configFile: false,
  logLevel: 'warn',
  build: {
    outDir,
    emptyOutDir: true,
    target: 'safari15',
    cssCodeSplit: false,
    lib: {
      entry: join(pkg, 'src/main.ts'),
      formats: ['iife'],
      name: 'AlmaTerminal',
      fileName: () => 'terminal.js',
      cssFileName: 'terminal',
    },
  },
})

const js = readFileSync(join(outDir, 'terminal.js'), 'utf8')
const css = readFileSync(join(outDir, 'terminal.css'), 'utf8')
const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>${css}</style></head><body><div id="term"></div>
<script>${js.replace(/<\/script/g, '<\\/script')}</script></body></html>`

const target = join(root, 'mobile/src/terminal/terminalHtml.ts')
mkdirSync(dirname(target), { recursive: true })
writeFileSync(
  target,
  '// Generated by scripts/build-terminal-web.mjs from packages/terminal-web. Do not edit.\n' +
    `export const TERMINAL_HTML = ${JSON.stringify(html)}\n`,
)
console.log(`terminal page: ${(html.length / 1024).toFixed(0)} KiB → ${target}`)
